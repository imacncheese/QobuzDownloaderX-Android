def build_huffman(bits, vals):
    """Return {symbol: (code, length)} from a BITS/VALS table pair."""
    table, code, k = {}, 0, 0
    for length in range(1, 17):
        for _ in range(bits[length - 1]):
            table[vals[k]] = (code, length)
            code += 1
            k += 1
        code <<= 1
    return table


class BitWriter:
    def __init__(self):
        self.data = bytearray()
        self.acc = 0
        self.n = 0

    def write(self, value, length):
        for i in range(length - 1, -1, -1):
            self.acc = (self.acc << 1) | ((value >> i) & 1)
            self.n += 1
            if self.n == 8:
                self.data.append(self.acc & 0xFF)
                if self.acc & 0xFF == 0xFF:
                    self.data.append(0x00)   # byte stuffing
                self.acc = 0
                self.n = 0

    def flush(self):
        while self.n:
            self.write(1, 1)   # pad with 1s


def magnitude(v):
    a = abs(v)
    return a.bit_length()


def encode_block(bw, coeffs, dc_pred, dc_table, ac_table):
    diff = coeffs[0] - dc_pred
    size = magnitude(diff)
    code, length = dc_table[size]
    bw.write(code, length)
    if size:
        bw.write(diff - 1 if diff < 0 else diff, size)

    run = 0
    for i in range(1, 64):
        v = coeffs[i]
        if v == 0:
            run += 1
            continue
        while run > 15:
            code, length = ac_table[0xF0]
            bw.write(code, length)
            run -= 16
        size = magnitude(v)
        sym = (run << 4) | size
        code, length = ac_table[sym]
        bw.write(code, length)
        bw.write(v - 1 if v < 0 else v, size)
        run = 0
    if run:
        code, length = ac_table[0x00]   # EOB
        bw.write(code, length)
    return coeffs[0]


def seg(marker, payload):
    return bytes([0xFF, marker]) + struct.pack(">H", len(payload) + 2) + payload


# --- pixel data: a smooth gradient so DC coefficients are non-zero --------
pixels = [[((x * 8) % 256, (y * 8) % 256, 128) for x in range(W)] for y in range(H)]

mcu = []
for y in range(0, H, 8):
    for x in range(0, W, 8):
        block = [pixels[y + j][x + i][0] - 128 for j in range(8) for i in range(8)]
        mcu.append(block)

bw = BitWriter()
dc_luma = build_huffman(DC_LUMA_BITS, DC_LUMA_VALS)
ac_luma = build_huffman(AC_LUMA_BITS, AC_LUMA_VALS)
pred = 0
for block in mcu:
    coeffs = [0] * 64
    coeffs[0] = block[0]                      # keep it trivial: DC only
    pred = encode_block(bw, coeffs, pred, dc_luma, ac_luma)
bw.flush()

out = bytearray()
out += b"\xFF\xD8"                                    # SOI
out += seg(0xE0, b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00")   # APP0
out += seg(0xDB, bytes([0x00]) + bytes([16] * 64))    # DQT, all-ones quant
out += seg(0xC0, struct.pack(">BHHB", 8, H, W, 1) + bytes([1, 0x11, 0]))  # SOF0
out += seg(0xC4, bytes([0x00]) + bytes(DC_LUMA_BITS) + bytes(DC_LUMA_VALS))  # DHT DC0
